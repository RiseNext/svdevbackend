import type {
  CollectionAfterChangeHook,
  CollectionAfterDeleteHook,
  GlobalAfterChangeHook,
  PayloadRequest,
} from 'payload'

import { DEFAULT_QUEUE } from '@/lib/constants'
import { env } from '@/lib/env'

/**
 * ON-DEMAND ISR REVALIDATION (D-119 / D-012).
 *
 * 🔴 WHY THIS IS A COLLECTION HOOK AND NOT ENDPOINT LOGIC:
 * Payload's admin publishes through its OWN PublishButton, which issues an
 * ordinary Local API update. It will NEVER call a custom
 * `POST /admin/projects/{id}/publish`. Realistically 100% of real publishes
 * bypass any custom endpoint, so revalidation placed in an endpoint would never
 * run — and "publishing silently does nothing visible on the website" is the
 * single most confusing possible failure for an admin.
 *
 * 🔴 FIRE-AND-FORGET WITH RETRY. A revalidation failure must NEVER fail the
 * admin's save. The direct fetch gives immediacy; the job gives the retry.
 * The admin sees "Saved. The website may take a few minutes to update." — a
 * warning, never an error.
 *
 * ⚠️ The direct fetch deliberately does NOT receive `req`. The documented
 * async-hook footgun is that "an async call made with the same req, but NOT
 * awaited, may fail resulting in an OK response being returned with response
 * data that is not committed." This call is not awaited, so it must not carry
 * the transaction.
 */

const revalidate = async (req: PayloadRequest, paths: string[], tags: string[]): Promise<void> => {
  const url = env.REVALIDATE_WEBHOOK_URL
  const secret = env.REVALIDATE_SECRET

  if (!url || !secret) {
    // Expected in local development; a hard error in production is prevented by
    // the env schema's production requirements.
    req.payload.logger.debug({ paths }, 'revalidation skipped — webhook not configured')
    return
  }

  try {
    const res = await fetch(url, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ secret, paths, tags }),
      // A slow frontend must not hold a database transaction open.
      signal: AbortSignal.timeout(5_000),
    })

    if (!res.ok) {
      throw new Error(`revalidate webhook returned ${res.status}`)
    }

    req.payload.logger.info({ paths, tags }, 'revalidated')
  } catch (err) {
    req.payload.logger.warn({ err, paths }, 'direct revalidation failed — queueing retry')
    try {
      await req.payload.jobs.queue({
        task: 'revalidatePaths',
        input: { paths, tags },
        queue: DEFAULT_QUEUE,
      })
    } catch (queueErr) {
      // Both paths failed. The time-based `revalidate: 3600` floor on the
      // frontend is the final backstop, so the change still appears within an
      // hour — it is just not immediate.
      req.payload.logger.error(
        { err: queueErr, paths },
        'could not queue a revalidation retry — the change will appear on the next ISR window',
      )
    }
  }
}

export const revalidateProject: CollectionAfterChangeHook & CollectionAfterDeleteHook = (async (
  args: { req: PayloadRequest; doc?: Record<string, unknown>; context?: Record<string, unknown> },
) => {
  const { req, doc, context } = args
  if (context?.skipRevalidate) return doc

  const slug = typeof doc?.slug === 'string' ? doc.slug : null
  // 🔶 `/gallery` ADDED. That page is built entirely from the project set —
  // `getProjects()` then `getProject()` per slug, deduped by `src` — so a new
  // project's photographs belong in the wall as soon as it publishes. It was
  // missing because the route did not exist when this list was written.
  const paths = ['/', '/projects', '/gallery', '/sitemap.xml']
  if (slug) paths.push(`/projects/${slug}`)

  const tags = ['projects']
  if (slug) tags.push(`project:${slug}`)

  // Deliberately NOT awaited, and deliberately NOT carrying `req`.
  void revalidate(req, paths, tags)
  return doc
}) as CollectionAfterChangeHook & CollectionAfterDeleteHook

/**
 * `blog-posts` — the per-slug set, modelled on `revalidateProject` rather than
 * on `revalidateContent`.
 *
 * 🔴 WHY NOT `revalidateContent`. That factory takes a CLOSED tag union and
 * emits ONE static tag, so it cannot produce `blog:<slug>` — and the frontend
 * asks for both: `getBlogPosts()` tags `['blog']`, while `getBlogPost(slug)`
 * tags `['blog', 'blog:<slug>']` (`svfrontend/src/lib/api/blog.ts`). Emitting
 * only `blog` would leave an edited post's own page serving the previous copy
 * until the one-hour ISR floor expired.
 *
 * ⚠️ `/blog` AND `/blog/<slug>` ARE BOTH LISTED, not just the index. The detail
 * route is statically generated by `generateStaticParams`, so an edit that
 * changed only the body would otherwise keep serving the prerendered page.
 *
 * ⚠️ `/sitemap.xml` IS INCLUDED EVEN THOUGH THE SITEMAP DOES NOT YET LIST
 * POSTS. It is listed here because the frontend's `sitemap.ts` gains `/blog` in
 * this same change, and a publish that did not refresh it would leave the new
 * route absent from the index Google reads. Revalidating a path that does not
 * depend on this content is free; omitting one that does is a silent staleness
 * bug — which is why `revalidateProject` already over-lists in the same way.
 *
 * Used for afterChange AND afterDelete: unpublishing or archiving a post must
 * drop it from the index, which is the same refresh as publishing one.
 */
export const revalidateBlogPost: CollectionAfterChangeHook & CollectionAfterDeleteHook = (async (
  args: { req: PayloadRequest; doc?: Record<string, unknown>; context?: Record<string, unknown> },
) => {
  const { req, doc, context } = args
  if (context?.skipRevalidate) return doc

  const slug = typeof doc?.slug === 'string' ? doc.slug : null
  const paths = ['/blog', '/sitemap.xml']
  if (slug) paths.push(`/blog/${slug}`)

  const tags = ['blog']
  if (slug) tags.push(`blog:${slug}`)

  // Deliberately NOT awaited, and deliberately NOT carrying `req`.
  void revalidate(req, paths, tags)
  return doc
}) as CollectionAfterChangeHook & CollectionAfterDeleteHook

/**
 * `site-settings` needs a REVALIDATE-EVERYTHING path, distinct from the
 * per-project set: it feeds `layout.tsx`, `PillNav`, `Footer` and `robots.txt`,
 * so a changed phone number affects every page on the site.
 *
 * 🔶 THE PATH LIST WAS CORRECTED, AND THE THREE REMOVALS ARE THE POINT.
 * `/location`, `/master-plan` and `/amenities` were revalidated here until the
 * frontend DELETED all three routes (commit `d47d8a7`, shipped in `acd9f7d` —
 * verified: each returns 404 in production). `revalidatePath` on a route that
 * does not exist is harmless, but leaving them was a standing lie about what
 * this global feeds, and it hid the two genuine omissions below.
 *
 * `/blog` and `/gallery` ARE THE ADDITIONS, and both are real dependencies:
 * every page renders `PillNav` and `Footer` from this global, so a changed
 * phone number or logo must reach them exactly as it reaches `/about`.
 * `/gallery` additionally reads the project set.
 */
export const revalidateEverything: GlobalAfterChangeHook = async ({ req, doc, context }) => {
  if (context?.skipRevalidate) return doc
  void revalidate(
    req,
    ['/', '/projects', '/about', '/contact', '/blog', '/gallery', '/sitemap.xml'],
    ['site-settings', 'projects'],
  )
  return doc
}

/**
 * Tier-2 content: one tag per resource, plus the pages that render them.
 *
 * 🔴 TYPED AS THE INTERSECTION so it can be wired to `afterDelete` AS WELL AS
 * `afterChange`, which is what the three tier-2 collections now do. It was
 * `CollectionAfterChangeHook` alone, and `tsc` correctly rejected the
 * `afterDelete` wiring: the delete hook's args carry no `data`, `operation` or
 * `previousDoc`. The cast mirrors `revalidateProject` and `revalidateBlogPost`,
 * which have always been declared this way for the same reason — this function
 * reads only `req`, `doc` and `context`, all three of which both hook shapes
 * provide.
 */
export const revalidateContent = (
  tag: 'testimonials' | 'faqs' | 'statistics',
  paths: string[],
): CollectionAfterChangeHook & CollectionAfterDeleteHook =>
  (async (args: {
    req: PayloadRequest
    doc?: Record<string, unknown>
    context?: Record<string, unknown>
  }) => {
    const { req, doc, context } = args
    if (context?.skipRevalidate) return doc
    void revalidate(req, paths, [tag])
    return doc
  }) as CollectionAfterChangeHook & CollectionAfterDeleteHook
